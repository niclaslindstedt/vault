// keeps the domain choice in the app ("store stays in the app"): it reuses the
// framework paths where they fit and adds the many marks a vault's categories
// want. Categories, folders and the appearance picker all draw from here.
//
// Pure data + a resolver — no React, so ordering and coverage are
// unit-testable in node (see `tests/glyphs_test.ts`). The framework's `Glyph`
// / `GlyphPicker` draw these, handed the render map via their `paths` prop.
//
