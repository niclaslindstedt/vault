/** Default glyph for a category that hasn't picked one. */
export const DEFAULT_CATEGORY_GLYPH = "folder";

/** Resolve a glyph name to its inner SVG, falling back to the default mark so
 *  a stale name (a removed custom glyph) still draws something. */
export function vaultGlyphPath(name: string | undefined): string {
  return (
    VAULT_GLYPH_PATHS[name ?? DEFAULT_CATEGORY_GLYPH] ??
    VAULT_GLYPH_PATHS[DEFAULT_CATEGORY_GLYPH]
  );
}
